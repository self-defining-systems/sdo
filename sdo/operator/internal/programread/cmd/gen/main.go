package main

import (
	"fmt"
	"go/format"
	"reflect"
	"sort"
	"strings"

	"sdo.dev/operator/safefs"
	"sdo.dev/operator/sdk/program"
)

func main() {
	t := reflect.TypeFor[program.ReadView]()
	imports := map[string]string{}
	var typename func(reflect.Type) string
	typename = func(t reflect.Type) string {
		if t.Name() != "" {
			if t.PkgPath() == "" {
				return t.Name()
			}
			p := t.PkgPath()
			a := imports[p]
			if a == "" {
				a = fmt.Sprintf("p%d", len(imports))
				imports[p] = a
			}
			return a + "." + t.Name()
		}
		switch t.Kind() {
		case reflect.Pointer:
			return "*" + typename(t.Elem())
		case reflect.Slice:
			return "[]" + typename(t.Elem())
		case reflect.Map:
			return "map[" + typename(t.Key()) + "]" + typename(t.Elem())
		}
		panic(t.String())
	}
	var body, replay strings.Builder
	for i := 0; i < t.NumMethod(); i++ {
		m := t.Method(i)
		var args, rets, names, outs []string
		haserr := false
		for j := 0; j < m.Type.NumIn(); j++ {
			n := fmt.Sprintf("a%d", j)
			args = append(args, n+" "+typename(m.Type.In(j)))
			names = append(names, n)
		}
		for j := 0; j < m.Type.NumOut(); j++ {
			rt := m.Type.Out(j)
			n := fmt.Sprintf("r%d", j)
			rets = append(rets, n+" "+typename(rt))
			if rt == reflect.TypeFor[error]() {
				haserr = true
			} else {
				outs = append(outs, "&"+n)
			}
		}
		fmt.Fprintf(&body, "func(v *View) %s(%s) (%s) {\nerr:=v.call(%q, []any{%s}, []any{%s})\n", m.Name, strings.Join(args, ","), strings.Join(rets, ","), m.Name, strings.Join(names, ","), strings.Join(outs, ","))
		if haserr {
			fmt.Fprintf(&body, "r%d=err\n", m.Type.NumOut()-1)
		} else if m.Name == "QueryMetrics" {
			body.WriteString("if err!=nil {r0.Query=a0; r0.Error=err.Error()}\n")
		} else {
			body.WriteString("if err!=nil {v.abort(err)}\n")
		}
		body.WriteString("return\n}\n")

		fmt.Fprintf(&replay, "func (v *replayFrameView) %s(%s) (%s) {\nif v.limited(%q, []any{%s}) {\n", m.Name, strings.Join(args, ","), strings.Join(rets, ","), m.Name, strings.Join(names, ","))
		sdkAlias := imports["sdo.dev/operator/sdk"]
		switch {
		case haserr:
			fmt.Fprintf(&replay, "r%d=%s.ErrReadReplyLimit\nreturn\n", m.Type.NumOut()-1, sdkAlias)
		case m.Name == "QueryMetrics":
			fmt.Fprintf(&replay, "r0.Query=a0; r0.Error=%s.ErrReadReplyLimit.Error(); return\n", sdkAlias)
		default:
			replay.WriteString("v.abort()\n")
		}
		fmt.Fprintf(&replay, "}\nreturn v.ReadView.%s(%s)\n}\n", m.Name, strings.Join(names, ","))
	}
	writeSource(".", "view_generated.go", "programread", body.String(), imports)
	writeSource("../../sdk/sdktest", "replay_frame_generated.go", "sdktest", replay.String(), imports)
}

func writeSource(root, file, pkg, body string, imports map[string]string) {
	var source strings.Builder
	fmt.Fprintf(&source, "// Code generated by go generate ./internal/programread; DO NOT EDIT.\npackage %s\nimport(\n", pkg)
	keys := []string{}
	for p := range imports {
		keys = append(keys, p)
	}
	sort.Strings(keys)
	for _, p := range keys {
		fmt.Fprintf(&source, "%s %q\n", imports[p], p)
	}
	source.WriteString(")\n")
	source.WriteString(body)
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		panic(err)
	}
	if err := safefs.WriteFile(root, file, formatted, 0o644); err != nil {
		panic(err)
	}
}
