// WorkloadSummary is one workload of a rendered inventory: its plan ID
// (Kind/Namespace/Name) and the container images its pods run.
type WorkloadSummary struct {
	ID string `json:"id"`
	// Identity is the stable form of ID: ID with a generated name suffix
	// replaced by `*` (see StableWorkloadID). A plan written from it keeps
	// matching the next release's render.
	Identity string   `json:"identity"`
	Images   []string `json:"images"`
}

// WorkloadInventory is what a deployment plan needs from a rendered inventory:
// every pod-bearing object (the pod-template table decides which) as an
// expected workload ID, and the sorted unique images of all of them.
type WorkloadInventory struct {
	Workloads []WorkloadSummary `json:"workloads"`
	Images    []string          `json:"images"`
	// Identities are the sorted unique stable workload identities and
	// Repositories the sorted unique image repositories (no tag, no digest):
	// the release-independent forms a plan declares so that an upstream change
	// of tags or generated names advances without a new plan.
	Identities   []string `json:"identities"`
	Repositories []string `json:"repositories"`
}

// SummarizeWorkloads derives the plan's workload IDs and images from rendered
// objects, in render order. namespace defaults objects that name none.
func SummarizeWorkloads(objects []*unstructured.Unstructured, namespace string) WorkloadInventory {
	inventory := WorkloadInventory{Workloads: []WorkloadSummary{}, Images: []string{}, Identities: []string{}, Repositories: []string{}}
	seen := map[string]bool{}
	for _, object := range objects {
		if !WorkloadKind(object.GetKind()) {
			continue
		}
		podSpec, err := PodSpec(object.Object)
		if err != nil {
			continue // not a usable pod template; the deploy path rejects it
		}
		ns := object.GetNamespace()
		if ns == "" {
			ns = namespace
		}
		workload := WorkloadSummary{ID: object.GetKind() + "/" + ns + "/" + object.GetName(), Images: []string{}}
		workload.Identity = StableWorkloadID(object.GetKind(), ns, object.GetName())
		for _, field := range ContainerFields {
			containers, _ := podSpec[field].([]any)
			for _, raw := range containers {
				container, _ := raw.(map[string]any)
				if image, _ := container["image"].(string); image != "" {
					workload.Images = append(workload.Images, image)
					if !seen[image] {
						seen[image] = true
						inventory.Images = append(inventory.Images, image)
					}
				}
			}
		}
		inventory.Workloads = append(inventory.Workloads, workload)
	}
	sort.Strings(inventory.Images)
	for _, workload := range inventory.Workloads {
		inventory.Identities = appendUnique(inventory.Identities, workload.Identity)
	}
	for _, image := range inventory.Images {
		inventory.Repositories = appendUnique(inventory.Repositories, imagesrc.Repository(image))
	}
	sort.Strings(inventory.Identities)
	sort.Strings(inventory.Repositories)
	return inventory
}

func appendUnique(list []string, value string) []string {
	if slices.Contains(list, value) {
		return list
	}
	return append(list, value)
}

// generatedToken is the grammar of a generated name suffix a plan's `*`
// stands for: lowercase letters and digits, five to ten of them (a hash of the
// workload's inputs, as Helm charts and Kustomize name Jobs and ConfigMaps).
var generatedToken = regexp.MustCompile(`^[a-z0-9]{5,10}$`)

// hashLike is a generated token SDO proposes a pattern for: it also contains a
// digit, so a plain word such as "migrate" is never taken for a hash.
func hashLike(token string) bool {
	return generatedToken.MatchString(token) && strings.ContainsAny(token, "0123456789")
}

// StableWorkloadID is the plan identity of a workload: Kind/Namespace/Name
// where a Job's generated name suffix (`-<hash>`, five to ten lowercase
// alphanumerics with a digit) is replaced by `*`. Jobs are the only kind
// whose name is regenerated by a release that changes only its inputs;
// a Deployment, StatefulSet or DaemonSet renamed by a release is a different
// workload and keeps its literal name.
func StableWorkloadID(kind, namespace, name string) string {
	return kind + "/" + namespace + "/" + StableWorkloadName(kind, name)
}

// StableWorkloadName is the name part of StableWorkloadID.
func StableWorkloadName(kind, name string) string {
	if kind == "Job" {
		if prefix, token, ok := cutLast(name, "-"); ok && prefix != "" && hashLike(token) {
			return prefix + "-*"
		}
	}
	return name
}

func cutLast(s, sep string) (before, after string, ok bool) {
	i := strings.LastIndex(s, sep)
	if i < 0 {
		return s, "", false
	}
	return s[:i], s[i+len(sep):], true
}

// MatchWorkloadID reports whether the rendered workload ID matches a plan
// entry: equal, or the entry is `Kind/Namespace/<prefix>-*` and the ID's name
// is <prefix>- followed by one generated token.
func MatchWorkloadID(entry, id string) bool {
	if entry == id {
		return true
	}
	prefix, ok := strings.CutSuffix(entry, "-*")
	if !ok || strings.Contains(prefix, "*") {
		return false
	}
	token, ok := strings.CutPrefix(id, prefix+"-")
	return ok && generatedToken.MatchString(token)
}

// checkWorkloadPattern rejects a `*` anywhere but the final `-*` of the name.
func checkWorkloadPattern(entry string) error {
	if !strings.Contains(entry, "*") {
		return nil
	}
	parts := strings.Split(entry, "/")
	name := parts[len(parts)-1]
	if len(parts) != 3 || strings.Contains(parts[0]+parts[1], "*") || !strings.HasSuffix(name, "-*") || len(name) == 2 || strings.Contains(strings.TrimSuffix(name, "*"), "*") {
		return fmt.Errorf("expected workload %q: `*` is allowed only as the final -* of the name, standing for one generated suffix (Kind/Namespace/name-*)", entry)
	}
	return nil
}

// CheckExpectedWorkloads checks that the plan's expected workload entries are
// unique and nonempty and match exactly the workloads of the desired set: each
// workload is named by an entry and each entry names a workload. An entry is a
// workload ID (Kind/Namespace/Name) or, for a generated name, Kind/Namespace/
// prefix-* (StableWorkloadID), which matches that name in every release. Apply
// and the offline operability report share it.
func CheckExpectedWorkloads(set DesiredSet, expected []string) error {
	wanted := map[string]bool{}
	for _, id := range expected {
		if id == "" || wanted[id] {
			return errors.New("expected workload IDs must be unique and nonempty")
		}
		if err := checkWorkloadPattern(id); err != nil {
			return err
		}
		wanted[id] = true
	}
	used := map[string]bool{}
	for _, object := range set.Objects() {
		if !object.Workload {
			continue
		}
		id := object.Ref.Kind + "/" + object.Ref.Namespace + "/" + object.Ref.Name
		matched := false
		for _, entry := range expected {
			if MatchWorkloadID(entry, id) {
				used[entry], matched = true, true
			}
		}
		if !matched {
			return fmt.Errorf("workload %s is missing from deployment plan", id)
		}
	}
	for _, entry := range expected {
		if !used[entry] {
			return fmt.Errorf("expected workload %s differs from rendered manifests: no rendered workload matches it", entry)
		}
	}
	return nil
}

// ImageSites lists every container image of every workload in apply order,
// including ephemeral phases (their pods run those images too): init
// containers first, then regular containers, per workload.
func ImageSites(set DesiredSet) []string {
	var images []string
	for _, phase := range set.Phases {
		for _, object := range phase.Objects {
			if !object.Workload {
				continue
			}
			podSpec, err := PodSpec(object.Object.Object)
			if err != nil {
				continue // Normalize rejected this shape before it entered the set.
			}
			for _, field := range ContainerFields {
				containers, _ := podSpec[field].([]any)
				for _, raw := range containers {
					container, _ := raw.(map[string]any)
					image, _ := container["image"].(string)
					images = append(images, image)
				}
			}
		}
	}
	return images
}
