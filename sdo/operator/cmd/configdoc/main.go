// Command configdoc renders docs/config.md from settings.Config's tags and Default(), so the reference cannot drift
// from the code. scripts/gen_config_docs.sh runs it and check_errors.sh fails on any difference.
package main

import (
	"fmt"
	"os"
	"strings"
	"time"

	"sdo.dev/operator/contracts/settings"
	"sdo.dev/operator/sdk/traffic"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: configdoc OUTPUT.md")
		os.Exit(2)
	}
	if err := os.WriteFile(os.Args[1], []byte(render()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func render() string {
	var out strings.Builder
	out.WriteString(`# Operator configuration

<!-- Generated by sdo/operator/cmd/configdoc from contracts/settings; do not edit. Run scripts/gen_config_docs.sh. -->

Operator configuration is how long SDO waits and how it responds. App memory (` + "`.sdo/`" + `) decides what counts as broken;
nothing here changes what an accepted detector decides.

## Setting it

` + "`sdo-operator host`" + ` and ` + "`sdo-operator install-existing`" + ` resolve one configuration, in this order (later wins):

1. the defaults in this file;
2. each ` + "`--config FILE`" + ` (YAML, repeatable, applied in order; an unknown key is an error);
3. ` + "`SDO_<SECTION>_<KEY>`" + ` environment variables, derived from the YAML key path (the top-level ` + "`mode`" + ` is ` + "`SDO_MODE`" + `).
   A list or an object is JSON. A variable that starts with a section prefix but names no key is an error.

No knob has a command-line flag of its own; the flags of ` + "`host`" + ` and ` + "`install-existing`" + ` name only the installation
(repository, namespaces, images, Secrets, PVC, registry, source and plan, agent registrations, run bounds).

The installer writes the resolved result to the ` + "`sdo-config`" + ` ConfigMap, mounted read-only at ` + "`/etc/sdo/config.yaml`" + ` in the
operate and controller Jobs, which refuse to start without it; no policy value crosses their command lines. The controller
records the file under ` + "`.sdo-runtime/config.yaml`" + ` at start, its compiled child and its deployment health checks read that
record, and the evidence sink carries it to the run directory.

A value is read once, when a process starts; there is no hot reload. The ConfigMap's hash is part of the controller's
install fingerprint, so running ` + "`install-existing`" + ` again with a changed configuration replaces the running controller
(one way: the new values apply only through that replacement).

` + "`sdo-operator config print [--config FILE]...`" + ` prints the resolved YAML.

For one release, ` + "`host`" + ` and ` + "`install-existing`" + ` refuse to start while ` + "`SDO_CODE_PATH`" + ` or ` + "`SDO_RESPONDER_MENU`" + ` is set in their
environment; use ` + "`SDO_AGENT_CODE_PATH`" + ` and ` + "`SDO_RESPONSE_MENU`" + `.

## Benchmark profile

` + "`benchmarks/fuzzops/sdo-bench.yaml`" + ` is the profile every benchmark harness passes first. It sets only what differs from the
defaults above: ` + "`response.repair_policy: recorded-actions`" + `, ` + "`detection.self_heal_hold: 60s`" + `, and, to measure the upper bound of what
learned playbooks achieve alone, ` + "`response.after_playbook: wait`" + ` with ` + "`response.after_playbook_wait: 5m`" + `: after a playbook applied,
the agent is never dispatched; recovery gets the whole bound (slow readiness and windowed detectors need more than the
stage's default 90 seconds), then the incident escalates. Production keeps ` + "`agent`" + `.

## Keys
`)
	out.WriteString(settings.Markdown())
	out.WriteString(`
## App-memory defaults

These are not operator configuration. Each is authored per detector or probe in app memory; the SDK constant is the
fallback when a field is left unset.

| Value | Fallback | Source |
|---|---|---|
`)
	for _, row := range []struct {
		name, value, constant string
	}{
		{"probe health minimum duration", traffic.DefaultHealthMinDuration.String(), "traffic.DefaultHealthMinDuration"},
		{"probe SLO window (samples)", fmt.Sprint(traffic.DefaultWindow), "traffic.DefaultWindow"},
		{"probe SLO minimum samples", fmt.Sprint(traffic.DefaultMinSamples), "traffic.DefaultMinSamples"},
		{"probe SLO maximum sample age", traffic.DefaultMaxAge.String(), "traffic.DefaultMaxAge"},
		{"probe SLO maximum error rate", fmt.Sprint(traffic.DefaultMaxErrorRate), "traffic.DefaultMaxErrorRate"},
		{"probe SLO maximum timeout rate", fmt.Sprint(traffic.DefaultMaxTimeoutRate), "traffic.DefaultMaxTimeoutRate"},
		{"probe SLO maximum latency", (traffic.DefaultMaxLatency).Round(time.Millisecond).String(), "traffic.DefaultMaxLatency"},
	} {
		fmt.Fprintf(&out, "| %s | `%s` | `%s` |\n", row.name, row.value, row.constant)
	}
	out.WriteString(`
## Internal worker variables

These are written by the controller into worker Jobs, or read by ` + "`sdo-operator memory check`" + ` inside workers. They are
transport, not knobs, and keep their names.

`)
	for _, name := range settings.WorkerVariables() {
		fmt.Fprintf(&out, "- `%s`\n", name)
	}
	return out.String()
}
