func TestRequestMetricsEntriesAreCappedAndRestReported(t *testing.T) {
	root := t.TempDir()
	var ops, entries []string
	for i := 0; i < MaxRequestMetricEntries+2; i++ {
		s := string(rune('a' + i))
		ops = append(ops, "  - {id: op-"+s+", entry: {service: svc"+s+", port: 80, method: GET, path: /"+s+"}, path: [svc"+s+"]}")
		entries = append(entries, "  - {service: svc"+s+", metric: m, labels: {route: r, status: s}, errors: \"5..\"}")
	}
	writeEntriesMap(t, root, "operations:\n"+strings.Join(ops, "\n")+"\nentries:\n"+strings.Join(entries, "\n"))
	cfg, ok := plannedRequestMetrics(root)
	if !ok || len(cfg.Entries) != MaxRequestMetricEntries {
		t.Fatalf("entries = %d, ok %v", len(cfg.Entries), ok)
	}
	var unmeasured int
	for _, o := range cfg.Operations {
		if o.Unmeasurable != "" {
			unmeasured++
		}
	}
	if unmeasured != 2 {
		t.Fatalf("unmeasured operations = %d", unmeasured)
	}
}

// A memory generated by an older SDO installs: its generated request-metrics
// detector (before the marker, with the older template) is regenerated to the
// current one, while a hand-edited generated file is refused.
func TestPrepareRegeneratesAPriorGoGenerationAndRefusesAHandEdit(t *testing.T) {
	root := t.TempDir()
	writeEntriesMap(t, root, syntheticRequestMap)
	if err := PrepareHealthWith(root, HealthOptions{RequestMetrics: true}); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, layout.DetectorDir(layout.ClassHealth, RequestMetricsDetectorID), layout.DetectorFileName)
	current, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	// An older generation: no marker, an older template body.
	_, body, _ := strings.Cut(string(current), "\n")
	older := strings.Replace(body, "logs.Watch", "logs.OlderWatch", 1)
	if older == body {
		t.Fatal("fixture did not change the template")
	}
	if err := os.WriteFile(path, []byte(older), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := PrepareHealthWith(root, HealthOptions{RequestMetrics: true}); err != nil {
		t.Fatalf("a prior Go generation must be regenerated: %v", err)
	}
	if got, _ := os.ReadFile(path); string(got) != string(current) {
		t.Fatal("the stored detector did not end with the current template")
	}
	// A hand edit of a marked file is an error naming the file.
	if err := os.WriteFile(path, append(current, []byte("// edited\n")...), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := PrepareHealthWith(root, HealthOptions{RequestMetrics: true}); err == nil || !strings.Contains(err.Error(), "request-metrics/detector.go") {
		t.Fatalf("a hand-edited generated file = %v, want an error naming it", err)
	}
}
