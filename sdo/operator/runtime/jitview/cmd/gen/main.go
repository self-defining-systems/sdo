package main

import (
	"fmt"
	"os"
	"reflect"
	"sdo.dev/operator/sdk/program"
	"sort"
	"strings"
)

func main() {
	t := reflect.TypeFor[program.ReadView]()
	imports := map[string]string{}
	var typename func(reflect.Type) string
	typename = func(t reflect.Type) string {
		if t.Name() != "" {
			if t.PkgPath() == "" {
				return t.Name()
			}
			p := t.PkgPath()
			a := imports[p]
			if a == "" {
				a = fmt.Sprintf("p%d", len(imports))
				imports[p] = a
			}
			return a + "." + t.Name()
		}
		switch t.Kind() {
		case reflect.Pointer:
			return "*" + typename(t.Elem())
		case reflect.Slice:
			return "[]" + typename(t.Elem())
		case reflect.Map:
			return "map[" + typename(t.Key()) + "]" + typename(t.Elem())
		}
		panic(t.String())
	}
	var body strings.Builder
	for i := 0; i < t.NumMethod(); i++ {
		m := t.Method(i)
		var args, rets, names, outs []string
		haserr := false
		for j := 0; j < m.Type.NumIn(); j++ {
			n := fmt.Sprintf("a%d", j)
			args = append(args, n+" "+typename(m.Type.In(j)))
			names = append(names, n)
		}
		for j := 0; j < m.Type.NumOut(); j++ {
			rt := m.Type.Out(j)
			n := fmt.Sprintf("r%d", j)
			rets = append(rets, n+" "+typename(rt))
			if rt == reflect.TypeFor[error]() {
				haserr = true
			} else {
				outs = append(outs, "&"+n)
			}
		}
		fmt.Fprintf(&body, "func(v *View) %s(%s) (%s) {\nerr:=v.call(%q, []any{%s}, []any{%s})\n", m.Name, strings.Join(args, ","), strings.Join(rets, ","), m.Name, strings.Join(names, ","), strings.Join(outs, ","))
		if haserr {
			fmt.Fprintf(&body, "r%d=err\n", m.Type.NumOut()-1)
		} else {
			body.WriteString("if err!=nil {panic(err)}\n")
		}
		body.WriteString("return\n}\n")
	}
	var source strings.Builder
	source.WriteString("// Code generated by go generate; DO NOT EDIT.\npackage jitview\nimport(\n")
	keys := []string{}
	for p := range imports {
		keys = append(keys, p)
	}
	sort.Strings(keys)
	for _, p := range keys {
		fmt.Fprintf(&source, "%s %q\n", imports[p], p)
	}
	source.WriteString(")\n")
	source.WriteString(body.String())
	if err := os.WriteFile("view_generated.go", []byte(source.String()), 0644); err != nil {
		panic(err)
	}
}
