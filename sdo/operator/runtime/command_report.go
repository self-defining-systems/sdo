package runtime

import (
	"fmt"
	"reflect"
	"strings"

	contracts "sdo.dev/operator/contracts/gen/sdodev/contracts/v1alpha1"
	"sdo.dev/operator/sdk"
)

// CommandReport is the complete per-invocation file shared by single and
// multiple action tools. Actions retain the ordinary unmodified tool outputs.
type CommandReport struct {
	OptionReports []*contracts.MitigationReport `json:"option_reports" schema:"typed per-option execution reports in selection order"`
	Actions       []ToolResponse                `json:"actions" schema:"complete independent option outputs/receipts; overlapping writes refused"`
	Findings      []sdk.Finding                 `json:"findings" schema:"current findings with full evidence"`
	Fixed         []sdk.Finding                 `json:"fixed" schema:"absent since the before snapshot"`
	New           []sdk.Finding                 `json:"new" schema:"new fingerprint or changed evidence; possible regression"`
	Unchanged     []sdk.Finding                 `json:"unchanged" schema:"same fingerprint and evidence"`
}

// CommandReportSchema is generated from the owning Go types. Consumers use the
// checked-in JSON generated by cmd/tool-report-schema, never a hand-copied map.
func CommandReportSchema() map[string]string {
	result := map[string]string{}
	shape := reflect.TypeFor[CommandReport]()
	for i := 0; i < shape.NumField(); i++ {
		field := shape.Field(i)
		element := field.Type.Elem()
		if element.Kind() == reflect.Pointer {
			element = element.Elem()
		}
		if element == reflect.TypeFor[sdk.Finding]() && field.Name != "Findings" {
			result[field.Tag.Get("json")] = "array of Finding (findings[] shape): " + field.Tag.Get("schema")
			continue
		}
		keys := []string{}
		for _, name := range []string{"command", "summary", "program_runs", "report", "option_reports", "status", "rounds", "attempt_id", "detector_id", "fingerprint", "primary_resource", "evidence"} {
			for j := 0; j < element.NumField(); j++ {
				candidate := element.Field(j)
				key := strings.Split(candidate.Tag.Get("json"), ",")[0]
				if key == "-" {
					key = toSnake(candidate.Name)
				}
				if key == name {
					keys = append(keys, key)
					break
				}
			}
		}
		result[field.Tag.Get("json")] = fmt.Sprintf("array of {%s}: %s", strings.Join(keys, ","), field.Tag.Get("schema"))
	}
	return result
}
func toSnake(value string) string {
	switch value {
	case "OptionReports":
		return "option_reports"
	case "Report":
		return "report"
	case "Receipt":
		return "receipt"
	}
	return value
}

// FindingProgress is calculated only from independently observed controller
// snapshots. A changed evidence string is surfaced, never silently called fixed.
type FindingProgress struct {
	Fixed     []sdk.Finding `json:"fixed"`
	New       []sdk.Finding `json:"new"`
	Unchanged []sdk.Finding `json:"unchanged"`
}

func CompareFindingProgress(before, after []sdk.Finding) FindingProgress {
	prior := map[string]sdk.Finding{}
	current := map[string]sdk.Finding{}
	for _, finding := range before {
		prior[FindingFingerprint(finding)] = finding
	}
	for _, finding := range after {
		current[FindingFingerprint(finding)] = finding
	}
	result := FindingProgress{Fixed: []sdk.Finding{}, New: []sdk.Finding{}, Unchanged: []sdk.Finding{}}
	for key, finding := range prior {
		if _, ok := current[key]; !ok {
			result.Fixed = append(result.Fixed, finding)
		}
	}
	for key, finding := range current {
		if before, ok := prior[key]; !ok || before.Evidence != finding.Evidence {
			result.New = append(result.New, finding)
		} else {
			result.Unchanged = append(result.Unchanged, finding)
		}
	}
	sortFindings(result.Fixed)
	sortFindings(result.New)
	sortFindings(result.Unchanged)
	return result
}
