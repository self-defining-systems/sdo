"""Generate skill-visible contracts from the worker's actual protobuf and MCP schemas."""

from __future__ import annotations

import argparse
import asyncio
import inspect
import json
import tempfile
from pathlib import Path
from typing import get_args

from sdo.agents.responder.credentials import SKILLS_ROOT
from sdo.agents.responder.mutation_output import command_report_schema
from sdo.agents.responder.reflection_authoring import OpenPhase
from sdo.agents.responder.reflection_validation import validation_server
from sdo.agents.responder.tool_output import MAX_TOOL_REPLY_BYTES
from sdo.agents.responder.tools_cli import verification_help
from sdo.contracts import ReflectionResult, model_output_schema

CONTRACT_PATH = SKILLS_ROOT / "sdo-memory/references/runtime.md"


async def render_contract() -> str:
    schema = model_output_schema(ReflectionResult.DESCRIPTOR)
    sections = [
        "# Worker authoring contract\n\nGENERATED by sdo.agents.responder.skill_contracts; do not edit by hand.",
        "## Decision and session envelope\n\n"
        "The CLI decision file contains the unwrapped ReflectionResult below. "
        "The model's session answer contains incident_result=null and reflection=ReflectionResult. "
        "The worker task/result envelopes are transport-owned and are never authored by the model. "
        "The check_memory tool accepts the decision fields directly and writes the CLI file.\n\n"
        f"```json\n{json.dumps(schema, indent=2)}\n```",
        "## Mitigation menu and responder continuity\n\n"
        "The menu is a convenience over direct commands. It lists accepted Mitigators with their declared "
        "object and value parameters, plus registered raw actions as one-action plans. Execution uses the "
        "ordinary PlanExecutor under existing controller RBAC and always-on executor checks. "
        "The menu adds no selection ledger, quiescence, provenance, health-reader or credential-delta "
        "preconditions. Reports return what ran, per-action results, value provenance and any error to the "
        "same responder session, with up to five rounds per incident. Pick from the menu when an option "
        "fits; if it fails, read the report and pick another or fix it directly. "
        "Current unexplained objects have controller-checked removal options; typed failure reasons guide recovery. "
        "EnsureDatabaseUser accepts env or namespace-local ConfigMap key credential references, optionally "
        "narrowed to one literal assignment. Only the executor resolves values into private stdin; plans, "
        "receipts and recordings retain references. Direct Secret keys require a separate security review. "
        "Author Mitigators as "
        "self-contained repairs with declared parameters and specific failure context. Intermediate reports "
        "are not independent incident outcomes or program trust credit.",
        "## Controller verification and command reports\n\n"
        "Plain verification returns the cached controller verdict immediately. Waiting returns on stable "
        "independent closure, a new or reactivated finding, or timeout, without running detectors. "
        "Fresh detector evaluation remains the detect path. After verified closure, incident_verified "
        "adds an informational timestamp and message to every normal result; reads and reports continue. "
        "New mutations receive a typed incident_verified rejection receipt.\n\n"
        "Mutating commands always store complete per-action results, evidence, program runs, reports and receipts "
        "under $SDO_SESSION_SCRATCH/sdo-reports/<incident>/<sequence>-<command>.json. Their compact output "
        "states action and incident verdicts separately, compares controller cached finding sets by fingerprint "
        "and evidence (fixed/new/unchanged), and prints the file path and generated schema. A failed action "
        "line names the failure reason, exit code and first error line.\n\n"
        f"```json\n{json.dumps(command_report_schema(), indent=2)}\n```\n\n" + verification_help(),
        "## Supported open phase selections\n\n"
        + "\n".join(
            f"- When captured, filename: open@{phase}.json; provenance open_at: {phase}."
            for phase in get_args(OpenPhase)
        )
        + "\n- Fixed capture: fixed.json; selected open recordings: open@<phase>-recordings.json.\n"
        "Select only files actually supplied by the controller. "
        "Supported phase values do not promise capture availability.",
        "## Tool reply budget\n\n"
        f"A reflection tool reply over {MAX_TOOL_REPLY_BYTES} bytes is saved whole to a file; the reply names "
        "its size and path with a short partial head. Search or extract from that file; the head is not "
        "the whole result.",
    ]
    with tempfile.TemporaryDirectory() as directory:
        tools = await validation_server(Path(directory)).list_tools()
    sections.extend(f"## {tool.name}\n\n{inspect.cleandoc(tool.description or '').rstrip()}" for tool in tools)
    return "\n\n".join(sections) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = asyncio.run(render_contract())
    if args.check:
        if CONTRACT_PATH.read_text() != expected:
            raise SystemExit("runtime.md is stale: regenerate with python -m sdo.agents.responder.skill_contracts")
    else:
        CONTRACT_PATH.write_text(expected)


if __name__ == "__main__":
    main()
