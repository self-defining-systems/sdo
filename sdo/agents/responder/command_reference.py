"""Generate the responder's command reference from the CLI's own definitions."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from sdo.agents.responder import tools_cli
from sdo.agents.responder.mutation_output import command_report_schema

REFERENCE_PATH = Path(__file__).resolve().parents[2] / "skills/sdo-incident-response/references/commands.md"


def _render_full_reference() -> str:
    """Render deterministically without controller I/O or heavyweight worker imports."""
    parser = tools_cli._parser()
    subcommands = next(action for action in parser._actions if isinstance(action, argparse._SubParsersAction))
    purposes = {action.dest: action.help for action in subcommands._choices_actions}
    notes: dict[str, list[str]] = {}
    owners: dict[str, list[str]] = {}
    for name, command in subcommands.choices.items():
        notes[name] = []
        for paragraph in (command.epilog or "").split("\n\n"):
            paragraph = paragraph.strip()
            if not paragraph or paragraph == tools_cli.response_fields_help(name):
                continue
            if paragraph not in notes[name]:
                notes[name].append(paragraph)
                owners.setdefault(paragraph, []).append(name)
    sections = [
        "# Responder command reference\n\n"
        "GENERATED by `uv run python -m sdo.agents.responder.command_reference` from the CLI parser, "
        "its response definitions and the generated command-report schema. Do not edit by hand.",
        "## Output\n\n"
        "Use `--json` before or after the command; for `act`, put SDO options before the wrapped command's `--`. "
        "Read commands return bounded JSON; overflow envelopes point to the complete response file. "
        "their default text points to a complete JSON file. Mutations return a compact JSON envelope "
        "with `command`, `summary`, `details_file`, `incident_verified` and conditional "
        "`error`/`failure_reason`/`hint`. "
        "The envelope is limited to 2048 UTF-8 bytes; query `details_file` for complete evidence. "
        "The worker provides `jq` for JSON extraction.\n\n"
        "Response keys below are conditional: absence is not success or health. Ordinary responses share "
        "`command`, `summary`, `healthy`, optional `error` and optional `incident_verified.{verified_at,message}`. "
        "Only independent verification establishes recovery. A pending detector reason is unproven health. "
        "Closed-incident reads/reports remain available; new mutations are rejected.\n\n"
        "Mutation files contain these generated top-level arrays:\n\n"
        + "\n".join(
            f"- `{key}[]`: {value.removeprefix('array of ')}" for key, value in command_report_schema().items()
        ),
    ]
    global_options = [
        "- `" + ", ".join(action.option_strings) + "`: " + str(action.help)
        for action in parser._actions
        if action.option_strings and action.help != argparse.SUPPRESS
    ]
    sections.append("## Global arguments\n\n" + "\n".join(global_options))
    if parser.description or parser.epilog:
        sections.append(
            "## General help\n\n```text\n" + "\n\n".join(filter(None, (parser.description, parser.epilog))) + "\n```"
        )
    sections.extend(
        "## Shared help: " + ", ".join(names) + "\n\n```text\n" + paragraph + "\n```"
        for paragraph, names in owners.items()
        if len(names) > 1
    )
    for name, command in subcommands.choices.items():
        usage = " ".join(command.format_usage().removeprefix("usage: ").split())
        parts = [f"## {name}\n\n{purposes[name]}\n\n```text\n{usage}\n```"]
        if command.description:
            parts.append(command.description)
        arguments = []
        for action in command._actions:
            if action.dest in {"help", "json"}:
                continue
            label = ", ".join(action.option_strings) or action.dest
            if action.help and action.help != argparse.SUPPRESS:
                arguments.append(f"- `{label}`: {action.help}")
        if arguments:
            parts.append("\n".join(arguments))
        parts.extend(f"```text\n{paragraph}\n```" for paragraph in notes[name] if len(owners[paragraph]) == 1)
        parts.append(tools_cli.response_fields_help(name, markdown=True))
        sections.append("\n\n".join(parts))
    return "\n\n".join(sections) + "\n"


def render_reference_bundle() -> dict[str, str]:
    """One short command index, shared guidance and one file per registered command."""
    full = _render_full_reference()
    commands = tools_cli.command_surface()["commands"]
    index, *sections = full.split("\n\n## ")
    common = [index]
    files = {}
    for section in sections:
        heading = section.split("\n", 1)[0]
        if heading in commands:
            files[f"commands/{heading}.md"] = "## " + section.rstrip() + "\n"
        else:
            common.append("## " + section.rstrip())
    common.append("## Commands\n\n" + "\n".join(f"- [{name}](commands/{name}.md)" for name in commands))
    files["commands.md"] = "\n\n".join(common) + "\n"
    return files


def render_reference() -> str:
    return render_reference_bundle()["commands.md"]


def topic_links() -> str:
    skill = REFERENCE_PATH.parent.parent / "SKILL.md"
    original = skill.read_text()
    marker = "<!-- command-topics -->"
    base = original.split(marker, 1)[0].rstrip()
    linked = {match.split("#", 1)[0] for match in re.findall(r"\]\(([^)]+)\)", base)}
    topics = [name for name in sorted(render_reference_bundle()) if "references/" + name not in linked]
    return (
        base
        + "\n\n"
        + marker
        + "\n## Command topics\n\n"
        + "\n".join(f"- [{Path(name).stem}](references/{name})" for name in topics)
        + "\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed reference has drifted")
    parser.add_argument("--output", type=Path, default=REFERENCE_PATH)
    args = parser.parse_args(argv)
    bundle = render_reference_bundle()
    directory = args.output.parent
    expected = {args.output: bundle.pop("commands.md"), **{directory / name: text for name, text in bundle.items()}}
    existing = {args.output, *(directory / "commands").glob("*.md")}
    stale = []
    for path in sorted(existing | expected.keys()):
        text = expected.get(path)
        if args.check:
            if text is None or not path.is_file() or path.read_text() != text:
                stale.append(str(path))
        elif text is None:
            path.unlink()
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.output == REFERENCE_PATH:
        skill = REFERENCE_PATH.parent.parent / "SKILL.md"
        expected_skill = topic_links()
        if args.check:
            if skill.read_text() != expected_skill:
                stale.append(str(skill))
        else:
            skill.write_text(expected_skill)
    if stale:
        print(
            "Missing or stale command references; regenerate with "
            "uv run python -m sdo.agents.responder.command_reference:\n" + "\n".join(stale),
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
