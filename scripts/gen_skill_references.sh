#!/bin/bash
# Regenerate the skill references that are derived from code.
#
# sdo/skills/sdo-detector-authoring/references/sdk.md is generated from the Go
# detector SDK (sdo/operator/sdk) with `go doc`, so agents author against the
# real API instead of a hand-written copy. Run this after changing the SDK's
# exported API or docs and commit the diff. `--check` fails when the committed
# file is stale (the sdk module's Go tests run it).

set -euo pipefail

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
SDK_DIR="$PROJECT_ROOT/sdo/operator/sdk"
TARGET="$PROJECT_ROOT/sdo/skills/sdo-detector-authoring/references/sdk.md"

render() {
    cd "$SDK_DIR"
    cat <<'EOF'
# Detector SDK reference

GENERATED by scripts/gen_skill_references.sh from sdo/operator/sdk with `go doc`. Do not edit by hand.

Import paths: `sdo.dev/operator/sdk` (detector API), `sdo.dev/operator/sdk/sdktest` (test snapshots and
invariants), `sdo.dev/operator/sdk/servicehealth` (shared Service checks), `sdo.dev/operator/sdk/traffic`
(synthetic-traffic health, summary only). `sdktest.Snapshot` implements `sdk.DetectionContext`. Kubernetes
types come from `k8s.io/api`.

EOF
    for package in . ./sdktest ./servicehealth; do
        echo '```text'
        go doc -all "$package"
        echo '```'
        echo
    done
    echo '```text'
    go doc ./traffic
    echo '```'
}

if [ "${1:-}" = "--check" ]; then
    expected="$(mktemp)"
    trap 'rm -f "$expected"' EXIT
    render > "$expected"
    if ! diff -u "$TARGET" "$expected"; then
        echo "sdk.md is stale: run scripts/gen_skill_references.sh and commit the result" >&2
        exit 1
    fi
else
    render > "$TARGET"
fi
