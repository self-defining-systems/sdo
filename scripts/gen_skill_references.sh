#!/bin/bash
# Regenerate the detector and replay references from the Go SDK. --check fails
# when either committed reference is stale; SDK tests run it automatically.
set -euo pipefail

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
SDK_DIR="$PROJECT_ROOT/sdo/operator/sdk"
REFERENCE_DIR="$PROJECT_ROOT/sdo/skills/sdo-detector-authoring/references"

render() {
    local reference="$1"
    cd "$SDK_DIR"
    if [ "$reference" = "program-sdk.md" ]; then
        echo '# Program SDK reference'
    elif [ "$reference" = "sdk.md" ]; then
        echo '# Detector SDK reference'
    else
        echo '# Detector replay reference'
    fi
    cat <<'HEADER'

GENERATED by scripts/gen_skill_references.sh from sdo/operator/sdk with `go doc`. Do not edit by hand.

Current Go APIs follow.

HEADER
    local packages=(. ./servicehealth ./workloadhealth)
    if [ "$reference" = "program-sdk.md" ]; then
        packages=(./program)
    elif [ "$reference" = "replay.md" ]; then
        packages=(./sdktest)
    fi
    for package in "${packages[@]}"; do
        echo '```text'
        go doc -all "$package"
        echo '```'
        if [ "$reference" != "replay.md" ]; then
            echo
        fi
    done
    if [ "$reference" = "sdk.md" ]; then
        echo '```text'
        go doc ./traffic
        echo '```'
        echo
        echo '```text'
        go doc -all ./metrics
        echo '```'
    fi
}

expected="$(mktemp)"
trap 'rm -f "$expected"' EXIT
for reference in sdk.md replay.md program-sdk.md; do
    if [ "$reference" = "program-sdk.md" ]; then
        REFERENCE_DIR="$PROJECT_ROOT/sdo/skills/sdo-playbook-authoring/references"
    fi
    if [ "${1:-}" = "--check" ]; then
        render "$reference" > "$expected"
        if ! diff -u "$REFERENCE_DIR/$reference" "$expected"; then
            echo "$reference is stale: run scripts/gen_skill_references.sh and commit the result" >&2
            exit 1
        fi
    else
        render "$reference" > "$REFERENCE_DIR/$reference"
    fi
done
