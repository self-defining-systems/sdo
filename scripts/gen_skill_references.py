"""Generate short SDK indexes and bounded per-package API reference files."""

from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "sdo/operator/sdk"


def render_bundle(title: str, packages: tuple[str, ...], stem: str) -> dict[str, str]:
    files: dict[str, str] = {}
    links = []
    for package in packages:
        text = subprocess.run(
            ["go", "doc", "-all", package], cwd=SDK, check=True, text=True, capture_output=True
        ).stdout
        blocks = re.split(r"\n(?=(?:type|func|var|const) )", text)
        chunks: list[str] = []
        for block in blocks:
            if len(block.split()) > 1800:
                raise ValueError(f"{package}: one declaration exceeds the reference budget")
            if not chunks or len((chunks[-1] + block).split()) > 1800:
                chunks.append(block)
            else:
                chunks[-1] += "\n" + block
        for index, chunk in enumerate(chunks, 1):
            name = package.removeprefix("./").replace(".", "sdk")
            relative = f"{stem}/{name}-{index:02d}.md"
            label = f"{package}, part {index}"
            files[relative] = (
                f"# {title}: {label}\n\n"
                "GENERATED by scripts/gen_skill_references.sh; do not edit by hand.\n\n"
                f"```text\n{chunk.rstrip()}\n```\n"
            )
            links.append(f"- [{label}]({relative})")
    files[f"{stem}.md"] = (
        f"# {title}\n\nGENERATED by scripts/gen_skill_references.sh from Go package documentation. "
        "Read only the relevant API topic.\n\n" + "\n".join(links) + "\n"
    )
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bundles = (
        (
            "sdo-detector-authoring",
            "Detector SDK reference",
            (".", "./servicehealth", "./workloadhealth", "./observe", "./traffic", "./metrics"),
            "sdk",
        ),
        ("sdo-detector-authoring", "Detector replay reference", ("./sdktest",), "replay"),
        ("sdo-playbook-authoring", "Program SDK reference", ("./program", "./routing"), "program-sdk"),
    )
    failures = []
    for skill, title, packages, stem in bundles:
        directory = ROOT / "sdo/skills" / skill / "references"
        files = render_bundle(title, packages, stem)
        existing = {f"{stem}.md", *(str(path.relative_to(directory)) for path in (directory / stem).glob("*.md"))}
        for name in sorted(existing | files.keys()):
            path = directory / name
            expected = files.get(name)
            if args.check:
                if expected is None or not path.is_file() or path.read_text() != expected:
                    failures.append(str(path.relative_to(ROOT)))
            elif expected is None:
                path.unlink()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    if failures:
        raise SystemExit("Stale generated references; run scripts/gen_skill_references.sh:\n" + "\n".join(failures))


if __name__ == "__main__":
    main()
