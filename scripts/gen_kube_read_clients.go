//go:build ignore

// Generate the read-only built-in API from the pinned client-go interfaces.
// Run: go run scripts/gen_kube_read_clients.go <client-go module directory>
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type source struct {
	file    *ast.File
	aliases map[string]string
}
type iface struct {
	node   *ast.InterfaceType
	source source
}

var imports = map[string]string{}
var set = token.NewFileSet()

func alias(path string) string {
	if path == "context" {
		return "context"
	}
	return "k" + regexp.MustCompile(`[^a-zA-Z0-9]`).ReplaceAllString(path, "")
}
func render(n ast.Node, s source) string {
	var b bytes.Buffer
	printer.Fprint(&b, set, n)
	out := b.String()
	for old, path := range s.aliases {
		re := regexp.MustCompile(`\b` + old + `\.`)
		if re.MatchString(out) {
			a := alias(path)
			imports[a] = path
			out = re.ReplaceAllString(out, a+".")
		}
	}
	return out
}
func main() {
	if len(os.Args) < 2 || len(os.Args) > 3 {
		panic("client-go module directory and optional --check required")
	}
	groups, _ := filepath.Glob(filepath.Join(os.Args[1], "kubernetes/typed/*/*/*_client.go"))
	var body strings.Builder
	for _, groupFile := range groups {
		dir := filepath.Dir(groupFile)
		files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
		all := map[string]iface{}
		var groupName string
		for _, path := range files {
			if strings.HasSuffix(path, "_test.go") {
				continue
			}
			f, err := parser.ParseFile(set, path, nil, 0)
			if err != nil {
				panic(err)
			}
			s := source{file: f, aliases: map[string]string{}}
			for _, imp := range f.Imports {
				p, _ := strconv.Unquote(imp.Path.Value)
				a := filepath.Base(p)
				if imp.Name != nil {
					a = imp.Name.Name
				}
				s.aliases[a] = p
			}
			for _, d := range f.Decls {
				g, ok := d.(*ast.GenDecl)
				if !ok {
					continue
				}
				for _, spec := range g.Specs {
					t, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}
					i, ok := t.Type.(*ast.InterfaceType)
					if !ok {
						continue
					}
					all[t.Name.Name] = iface{i, s}
					if path == groupFile && strings.HasSuffix(t.Name.Name, "Interface") {
						groupName = t.Name.Name
					}
				}
			}
		}
		if groupName == "" {
			continue
		}
		group := all[groupName]
		short := strings.TrimSuffix(groupName, "Interface")
		local := "Read" + short
		rel, _ := filepath.Rel(os.Args[1], dir)
		path := "k8s.io/client-go/" + filepath.ToSlash(rel)
		a := alias(path)
		imports[a] = path
		fmt.Fprintf(&body, "type %s struct { client %s.%s }\n", local, a, groupName)
		fmt.Fprintf(&body, "func (c *ReadClient) %s() %s {return %s{client:c.builtin.%s()}}\n", short, local, local, short)
		for _, field := range group.node.Methods.List {
			id, ok := field.Type.(*ast.Ident)
			if !ok {
				continue
			}
			getter, ok := all[id.Name]
			if !ok {
				continue
			}
			for _, m := range getter.node.Methods.List {
				if len(m.Names) != 1 {
					continue
				}
				ft, ok := m.Type.(*ast.FuncType)
				if !ok || ft.Results == nil || len(ft.Results.List) != 1 {
					continue
				}
				result, ok := ft.Results.List[0].Type.(*ast.Ident)
				if !ok {
					continue
				}
				resource, ok := all[result.Name]
				if !ok {
					continue
				}
				name := local + strings.TrimSuffix(result.Name, "Interface")
				var methods []string
				var collect func(iface)
				collect = func(i iface) {
					for _, f := range i.node.Methods.List {
						if len(f.Names) == 0 {
							if x, ok := f.Type.(*ast.Ident); ok {
								if exp, found := all[x.Name]; found {
									collect(exp)
								}
							}
							continue
						}
						n := f.Names[0].Name
						if n != "Get" && n != "List" && n != "Watch" && n != "GetScale" && n != "GetLogs" && n != "ProxyGet" {
							continue
						}
						sig := render(f.Type, i.source)
						methods = append(methods, n+strings.TrimPrefix(sig, "func"))
					}
				}
				collect(resource)
				if len(methods) == 0 {
					continue
				}
				fmt.Fprintf(&body, "type %s interface {\n%s\n}\n", name, strings.Join(methods, "\n"))
				sig := render(ft, getter.source)
				sig = strings.TrimPrefix(sig, "func")
				sig = strings.TrimSuffix(sig, result.Name) + name
				var args []string
				for _, p := range ft.Params.List {
					for _, n := range p.Names {
						args = append(args, n.Name)
					}
				}
				fmt.Fprintf(&body, "func(c %s) %s%s {return c.client.%s(%s)}\n", local, m.Names[0].Name, sig, m.Names[0].Name, strings.Join(args, ","))
			}
		}
	}
	var out strings.Builder
	out.WriteString("// Code generated by scripts/gen_kube_read_clients.go; DO NOT EDIT.\npackage kubeclient\nimport (\n")
	keys := make([]string, 0, len(imports))
	for k := range imports {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&out, "%s %q\n", k, imports[k])
	}
	out.WriteString(")\n")
	out.WriteString(body.String())
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	target := "sdo/operator/sdk/kubeclient/builtins_generated.go"
	if len(os.Args) == 3 {
		if os.Args[2] != "--check" {
			panic("unknown generator option")
		}
		old, err := os.ReadFile(target)
		if err != nil || !bytes.Equal(old, formatted) {
			fmt.Fprintln(os.Stderr, "read client facade is stale: run bash scripts/gen_kube_read_clients.sh")
			os.Exit(1)
		}
		return
	}
	if err = os.WriteFile(target, formatted, 0644); err != nil {
		panic(err)
	}
}
