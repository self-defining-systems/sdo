"""The generated Python messages parse what the Go controller writes.

The fixtures under ``tests/fixtures/sdo/contracts/go/`` are generated by
``sdo/operator/runtime/contract_golden_test.go`` from the controller's real
encode paths (a real incident for the request, the published view and the
closures), and that Go test fails whenever the encoding drifts from them.
RC1's ``changes: null`` wedge passed both sides' unit tests because each
side built its values in its own language; these tests close that gap.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from sdo.agents.responder.incident_status import _controller_view
from sdo.contracts import (
    BrokerLedger,
    ControllerState,
    IncidentClosure,
    IncidentRequest,
    IncidentView,
    parse_json,
    timestamp_datetime,
)
from tests.proto_messages import from_dict

GO_FIXTURES = Path(__file__).resolve().parents[3] / "fixtures" / "sdo" / "contracts" / "go"
VIEWS = ("incident_view_empty.json", "incident_view_open.json", "incident_view_populated.json")
CLOSURES = ("closure_repaired.json", "closure_own_edit.json")


def _text(name: str) -> str:
    return (GO_FIXTURES / name).read_text(encoding="utf-8")


def _raw(name: str) -> Any:
    return json.loads(_text(name))


def _nulls(value: Any, path: str = "$") -> list[str]:
    if value is None:
        return [path]
    if isinstance(value, dict):
        return [found for key, child in value.items() for found in _nulls(child, f"{path}.{key}")]
    if isinstance(value, list):
        return [found for index, child in enumerate(value) for found in _nulls(child, f"{path}[{index}]")]
    return []


def test_every_go_fixture_is_present_and_null_free() -> None:
    names = sorted(path.name for path in GO_FIXTURES.glob("*.json"))

    assert names == sorted(
        [
            *VIEWS,
            *CLOSURES,
            "incident_request.json",
            "controller_state.json",
            "broker_ledger.json",
        ]
    )
    for name in names:
        assert _nulls(_raw(name)) == [], name


@pytest.mark.parametrize("name", VIEWS)
def test_incident_status_accepts_the_controllers_published_view(name: str) -> None:
    raw = _raw(name)

    view, reason = _controller_view("demo/sdo-controller-state", lambda _: json.dumps({"incident_view": raw}), None)

    assert view is not None, reason
    assert view == parse_json(_text(name), IncidentView())


def test_the_views_clearing_findings_and_changes_round_trip() -> None:
    empty = parse_json(_text("incident_view_empty.json"), IncidentView())
    populated = parse_json(_text("incident_view_populated.json"), IncidentView())

    assert (list(empty.blocking_findings), list(empty.clearing_findings)) == ([], [])
    assert empty.HasField("state_changes")
    assert list(empty.state_changes.changes) == []
    assert [finding.fingerprint for finding in populated.blocking_findings] == ["cause"]
    assert [finding.fingerprint for finding in populated.clearing_findings] == ["clearing"]
    assert populated.HasField("state_changes")
    assert [(change.kind, change.change) for change in populated.state_changes.changes] == [
        ("Service", "modified"),
        ("ConfigMap", "removed"),
    ]
    assert list(populated.state_changes.unobserved_kinds) == ["Secret"]


def test_a_cold_incidents_request_parses() -> None:
    request = parse_json(_text("incident_request.json"), IncidentRequest())

    assert list(request.surfaced_playbooks) == []
    assert list(request.relevant_outcomes) == []
    assert request.HasField("state_changes")
    assert [change.name for change in request.state_changes.changes] == ["frontend"]


def test_a_repaired_closure_carries_the_f17_facts() -> None:
    closure = parse_json(_text("closure_repaired.json"), IncidentClosure())

    assert timestamp_datetime(closure.verified_at) >= timestamp_datetime(closure.dispatched_at)
    assert closure.HasField("final_state_changes")
    assert list(closure.final_state_changes.changes) == []
    assert closure.HasField("health_cleared_at")
    assert closure.HasField("result")
    assert [(ref.kind, ref.name) for ref in closure.result.repair_actions[0].resources] == [("Service", "frontend")]
    assert [(item.kind, item.name) for item in closure.observed_state_changes] == [("Service", "frontend")]


def test_a_wrong_fix_citing_its_own_edit_is_contradicted_from_go_facts() -> None:
    closure = parse_json(_text("closure_own_edit.json"), IncidentClosure())

    assert closure.HasField("result")
    [observed] = closure.observed_state_changes
    assert observed.first_observed_at.ToNanoseconds() > closure.result.repair_actions[0].started_at.ToNanoseconds()


def test_the_controllers_persisted_state_is_protojson_the_status_command_reads() -> None:
    text = _text("controller_state.json")

    state = parse_json(text, ControllerState())
    view, reason = _controller_view("demo/sdo-controller-state", lambda _: text, None)

    assert state.incident_open
    assert state.pending_closure.request.incident_id == state.incident_request.incident_id
    assert view is not None, reason
    assert view == state.incident_view
    assert [finding.fingerprint for finding in view.blocking_findings] == ["fp"]


def test_the_brokers_ledger_is_protojson_the_receipt_reads() -> None:
    ledger = parse_json(_text("broker_ledger.json"), BrokerLedger())
    raw = _raw("broker_ledger.json")

    assert ledger.acknowledged
    assert ledger.receipt.ack_token == "token"
    assert ledger.closure.request.incident_id == ledger.incident_id
    # The strict native receipt reads the same raw document without legacy keys.
    assert raw["closure"]["request"]["incident_id"] == raw["incident_id"]


def test_a_latent_incident_carries_classified_drift() -> None:
    raw = _raw("incident_request.json")
    raw["findings"][0]["severity"] = "latent"
    raw["drift_events"] = [
        {
            "ref": {"api_version": "v1", "kind": "Service", "namespace": "demo", "name": "frontend"},
            "fields": [{"path": "spec.ports[0].targetPort", "old": "8080", "new": "9999"}],
            "source": "differs from accepted manifest",
            "manager": "unknown-editor",
            "operation": "Update",
            "observed_at": "1970-01-01T00:00:01Z",
            "classification": "fault",
            "program_id": "targetport",
        }
    ]

    request = from_dict(IncidentRequest, raw)

    assert request.findings[0].severity == "latent"
    assert request.drift_events[0].program_id == "targetport"
