// submitOnly is every refusal `Add` (the submit path) makes itself instead of through ValidateRendered, which `plan
// add` and `--dry-run` also call. A rule belongs in ValidateRendered unless it needs something only a submit has:
// the experiment's name taken in this root, the content of an input stored for the lock (an artifact edge's file),
// the hooks' own check run on those stored inputs, or a plain I/O failure. Growing this list is a deliberate act: say
// why the rule cannot run at add time.
var submitOnly = []string{
	"LoadSpec",      // reading the spec file (add time has the rendered bytes, which ValidateRendered checks)
	"lockAdds",      // the root's add lock: runtime state
	"LoadInventory", // I/O (add time loads it too)
	"Store",         // storing an input by content: I/O on the file's content
	"hookCheck",     // the hooks' own check runs on the stored inputs, the seed's content included
	"writeJSON",     // writing the lock
	"os.ReadFile",   // reading the spec to copy it
	"writeFile",     // writing the spec copy
	"%s exists: experiment names are never reused", // the name is generated by the plan; whether it is taken is root state
	"faults.instances: %w",                         // storing the instances file (its IDs are checked by ValidateRendered)
	"operator.baseline: %w",                        // storing the baseline directory
	"operator.seed: %w",                            // the seed is an earlier arm's artifact: only a submit has its content
}

// addRefusals lists what Add can return as an error: the format of each fmt.Errorf, and the callee of each call that
// can fail for its own reason.
func addRefusals(t *testing.T) (refusals []string, callsValidate bool) {
	f, err := parser.ParseFile(token.NewFileSet(), "verbs.go", nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	callee := func(c *ast.CallExpr) string {
		switch fn := c.Fun.(type) {
		case *ast.Ident:
			return fn.Name
		case *ast.SelectorExpr:
			if id, ok := fn.X.(*ast.Ident); ok {
				return id.Name + "." + fn.Sel.Name
			}
			return fn.Sel.Name
		}
		return ""
	}
	known := map[string]bool{"LoadSpec": true, "lockAdds": true, "LoadInventory": true, "hookCheck": true,
		"writeJSON": true, "os.ReadFile": true, "writeFile": true, "Store": true}
	seen := map[string]bool{}
	add := func(s string) {
		if !seen[s] {
			seen[s] = true
			refusals = append(refusals, s)
		}
	}
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Name.Name != "Add" {
			continue
		}
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			c, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			name := callee(c)
			switch {
			case name == "ValidateRendered":
				callsValidate = true
			case name == "fmt.Errorf" || name == "errors.New":
				if lit, ok := c.Args[0].(*ast.BasicLit); ok {
					add(strings.Trim(lit.Value, "\""))
				}
			case known[name]:
				add(name)
			}
			return true
		})
	}
	sort.Strings(refusals)
	return refusals, callsValidate
}

// Every refusal Add makes is reachable from `plan add` (through ValidateRendered) or is in submitOnly, and the list
// holds nothing Add no longer does.
func TestSubmitRefusalsAreReachableFromAddOrListedSubmitOnly(t *testing.T) {
	got, callsValidate := addRefusals(t)
	if !callsValidate {
		t.Fatal("Add does not call ValidateRendered")
	}
	want := append([]string(nil), submitOnly...)
	sort.Strings(want)
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("Add's own refusals differ from submitOnly: a new rule goes into ValidateRendered (so `plan add` runs it), or, if only a submit can run it, into submitOnly with the reason.\nAdd:        %q\nsubmitOnly: %q", got, want)
	}
}

// `plan add` runs ValidateRendered on every rendered spec.
func TestPlanSpecCheckCallsValidateRendered(t *testing.T) {
	f, err := parser.ParseFile(token.NewFileSet(), "planbackend.go", nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	found := false
	ast.Inspect(f, func(n ast.Node) bool {
		if c, ok := n.(*ast.CallExpr); ok {
			if id, ok := c.Fun.(*ast.Ident); ok && id.Name == "ValidateRendered" {
				found = true
			}
		}
		return true
	})
	if !found {
		t.Fatal("planSpecCheck does not call ValidateRendered")
	}
}
